-- =====================================================================
-- 0002 · Версия заказа в журнале изменений
--
-- Нужна, чтобы при конфликте оптимистической блокировки объяснить оператору,
-- ЧТО именно изменилось: сервис читает записи журнала с order_version больше
-- версии, с которой пришёл клиент, и превращает их в человекочитаемый список.
-- =====================================================================

ALTER TABLE order_audit_log
    ADD COLUMN order_version integer;

COMMENT ON COLUMN order_audit_log.order_version IS
    'Версия заказа, получившаяся после события. NULL допустим только для записей, созданных до этой миграции.';

-- Выборка «что произошло после версии N» — горячий путь при разборе конфликта.
CREATE INDEX idx_audit_order_version ON order_audit_log (order_id, order_version);
